"""内置默认提示词 —— 单一事实源（single source of truth）。

背景（P23）：同一组默认提示词此前在三个位置逐字重复：
  - core/ai_correction.py   —— 运行时 ``config.get(key, DEFAULT)`` 回落值
  - core/config_manager.py  —— 首次建文件（ensure_config_files）写入的模板
  - core/settings/domains.py —— 域对象 DEFAULTS

三份副本已经漂移：``polish_prompt`` 在 domains/config_manager 里是被截断的
``"你是一个专业的字幕润色专家。请对翻译/纠错后的字幕进行润色..."``，不含
``{待校对文本}`` 占位符，而 ai_correction 的副本含占位符。由于建文件时写入的
是前者，实际生效的润色提示词**永远没有正文** —— 模型收到一条不含待润色文本的
指令，返回内容与输入无关，润色结果被静默污染。

本模块不导入任何 core 内部模块，可被上述三方安全共享。
"""

# ── 纠错（校对）──────────────────────────────────────────────

DEFAULT_CORRECTION_PROMPT = "你是一个文本校对专家。请根据上下文纠正OCR识别结果中的明显错误，保留原格式。"

DEFAULT_CORRECTION_SYSTEM_PROMPT = (
    "你是一个专业的字幕校对助手。你接收带有时间轴的OCR识别文本列表，"
    "逐行校对，保持行数不变，只修正明显错误，不要合并或拆分条目。"
    "用户自定义提示词作为额外参考。只返回修正后的结果。"
)

DEFAULT_OUTPUT_FORMAT = "[纠正后文本]"

# ── 翻译 ────────────────────────────────────────────────────

DEFAULT_TRANSLATE_SYSTEM_PROMPT = (
    "你是一个专业的字幕翻译助手。你接收带有时间轴（起止时间）的OCR识别文本列表，"
    "将每行 OCR 文本翻译为中文。保持原始行号前缀 [ID:行号]，逐行翻译。"
    "如果上下文显示某行是不完整的碎片（与上一行或下一行属于同一句话），"
    "将完整语义合并到该行的翻译中，使每行译文语义完整自然。"
    "保持输出行数与输入一致，每个 [ID:行号] 对应一行。"
    "用户自定义提示词仅作为翻译风格参考。只返回翻译后的结果。"
)

# ── 环境信息提取 ─────────────────────────────────────────────

DEFAULT_SUMMARY_PROMPT = (
    "请根据以下OCR识别文本，总结出这段内容的：\n"
    "1. 领域/类型（如：小说、新闻、游戏对话、学术论文等）\n"
    "2. 整体氛围/语气（如：严肃、欢快、悲伤、紧张等）\n"
    "3. 主要内容/主题（一句话概括）\n\n"
    "请用简洁的中文回答，格式：\n"
    "领域：xxx\n氛围：xxx\n内容：xxx"
)

# ── 润色 ────────────────────────────────────────────────────
# 注意：必须保留 {待校对文本} 占位符，polish() 依赖它注入待润色正文。

DEFAULT_POLISH_PROMPT = (
    "你是一个专业的字幕润色专家。请对以下已翻译/纠错后的字幕文本进行润色：\n"
    "1. 调整语序使表达更自然流畅\n2. 统一术语和风格\n3. 精简冗余表达\n"
    "4. 确保符合中文字幕习惯\n\n"
    "原始文本：{原始结果}\n"
    "待润色文本：{待校对文本}\n\n"
    "请直接输出润色后的文本，不要附加说明。"
)

DEFAULT_POLISH_SYSTEM_PROMPT = "你是一个专业的字幕润色专家。只输出最终的润色结果文本。"

# 润色提示词必须包含的占位符（缺失时 polish() 会自动追加正文，见 ai_correction）
POLISH_TEXT_PLACEHOLDER = "{待校对文本}"


def is_placeholder_free_polish_prompt(prompt: str) -> bool:
    """润色提示词是否完全没有可用于注入正文的占位符。"""
    text = str(prompt or "")
    return "{待校对文本}" not in text and "{原始结果}" not in text
